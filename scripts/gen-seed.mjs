import { readFileSync, writeFileSync } from "node:fs"

const cards = JSON.parse(readFileSync(new URL("../data/cards.json", import.meta.url), "utf8"))
const q = (s) => "'" + String(s).replace(/'/g, "''") + "'"
const arr = (a) => "ARRAY[" + a.map(q).join(", ") + "]::text[]"
const n = (v) => (v == null ? "null" : v)

let sql = "-- Generated by scripts/gen-seed.mjs. Figures are unverified until reviewed against issuer documents.\n"
for (const c of cards) {
  sql += `insert into cards (slug,name,issuer,network,tagline,annual_fee,joining_fee,fee_waiver_spend,base_rate,eligibility,highlights,exclusions,source_url,colors,verification_status)
values (${q(c.slug)},${q(c.name)},${q(c.issuer)},${q(c.network)},${q(c.tagline)},${c.annual_fee},${c.joining_fee},${n(c.fee_waiver_spend)},${c.base_rate},${q(c.eligibility)},${arr(c.highlights)},${arr(c.exclusions)},${q(c.source_url)},${arr(c.colors)},'pending')
on conflict (slug) do update set name=excluded.name, issuer=excluded.issuer, network=excluded.network, tagline=excluded.tagline, annual_fee=excluded.annual_fee, joining_fee=excluded.joining_fee, fee_waiver_spend=excluded.fee_waiver_spend, base_rate=excluded.base_rate, eligibility=excluded.eligibility, highlights=excluded.highlights, exclusions=excluded.exclusions, source_url=excluded.source_url, colors=excluded.colors;\n`
  sql += `delete from reward_rules where card_id = (select id from cards where slug=${q(c.slug)});\n`
  for (const r of c.rules) {
    sql += `insert into reward_rules (card_id,category,rate_pct,monthly_cap,note) select id,${q(r.category)},${r.rate},${n(r.cap)},${r.note ? q(r.note) : "null"} from cards where slug=${q(c.slug)};\n`
  }
  sql += `insert into sources (card_id,url,kind) select id,${q(c.source_url)},'issuer_page' from cards where slug=${q(c.slug)} on conflict do nothing;\n`
}
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql)
console.log("wrote supabase/seed.sql for", cards.length, "cards")
